/** Writes assets/css/tokens.css from data/design.json: light values, dark values and fixed values. */

const GROUPS = ["color", "shadow"]
const HEADER = "/* Generated by tools/build.mjs from data/design.json. Do not edit. */"

function declaration(theme, [name, token]) {
  return `  --${name}: ${token[theme]};`
}

function groupEntries(design, group) {
  return Object.entries(design[group])
}

function themed(design, theme) {
  const entries = GROUPS.flatMap(groupEntries.bind(null, design))
  return entries.map(declaration.bind(null, theme)).join("\n")
}

function fixedDeclaration([name, value]) {
  return `  --${name}: ${value};`
}

function block(selector, scheme, body) {
  return `${selector} {\n  color-scheme: ${scheme};\n${body}\n}`
}

/** Light values on :root, dark values for a dark system setting, and dark values when the page asks for dark. */
export function renderTokens(design) {
  const fixed = Object.entries(design.fixed).map(fixedDeclaration).join("\n")
  const dark = themed(design, "dark")
  const light = block(":root", "light", `${themed(design, "light")}\n${fixed}`)
  const system = `@media (prefers-color-scheme: dark) {\n${block(':root:not([data-theme="light"])', "dark", dark)}\n}`
  const chosen = block(':root[data-theme="dark"]', "dark", dark)
  return `${HEADER}\n${light}\n\n${system}\n\n${chosen}\n`
}
