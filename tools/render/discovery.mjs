/** The files for search engines and agents: robots.txt, sitemap.xml, llms.txt, agents.txt and .well-known/agents.json. */

const BANNER = "# Generated by tools/build.mjs from the files in data/. Do not edit."

function isFeatured(project) {
  return project.tier === "featured"
}

function isOther(project) {
  return !isFeatured(project)
}

function crawlerBlock(name) {
  return `User-agent: ${name}\nAllow: /`
}

export function robotsTxt({ site, discovery }) {
  const blocks = discovery.crawlers.map(crawlerBlock).join("\n\n")
  return `${BANNER}\n${blocks}\n\nSitemap: ${site.url}sitemap.xml\n`
}

/** One page, so one entry. The date comes from git when the build runs. */
export function sitemapXml({ site }, lastModified) {
  const entry = `<url><loc>${site.url}</loc><lastmod>${lastModified}</lastmod></url>`
  return `<?xml version="1.0" encoding="UTF-8"?>\n<!-- Generated by tools/build.mjs. Do not edit. -->\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">${entry}</urlset>\n`
}

function projectLine(project) {
  return `- [${project.name}](${project.links.primary.href}): ${project.summary}`
}

function section(title, projects) {
  return `## ${title}\n\n${projects.map(projectLine).join("\n")}`
}

/** A short Markdown summary for language models. It has the links and no email address. */
export function llmsTxt({ site, projects }) {
  const all = projects.projects
  const contact = `## Contact\n\n- [${site.contactBand.bookingLabel}](${site.contact.bookingUrl})\n- [Contact section](${site.url}#contact)`
  const blocks = [`# ${site.name}`, `> ${site.description}`, section("Projects", all.filter(isFeatured)), section(site.more.heading, all.filter(isOther)), contact]
  return `${blocks.join("\n\n")}\n`
}

function rule(word, text) {
  return `${word}: ${text}`
}

function allowRule(text) {
  return rule("Allow", text)
}

function denyRule(text) {
  return rule("Disallow", text)
}

export function agentsTxt({ site, discovery }) {
  const { agents } = discovery
  const head = [BANNER, rule("Name", site.name), rule("Site", site.url), rule("Summary", agents.summary)]
  const rules = [...agents.may.map(allowRule), ...agents.mayNot.map(denyRule)]
  const tail = [rule("Contact", site.contact.bookingUrl), rule("Sitemap", `${site.url}sitemap.xml`), rule("LLMs", `${site.url}llms.txt`)]
  return `${[...head, ...rules, ...tail].join("\n")}\n`
}

export function agentsJson({ site, discovery }) {
  const { agents } = discovery
  const body = { name: site.name, url: site.url, summary: agents.summary, mayDo: agents.may, mayNotDo: agents.mayNot, contact: site.contact.bookingUrl, sitemap: `${site.url}sitemap.xml`, llms: `${site.url}llms.txt` }
  return `${JSON.stringify(body, null, 2)}\n`
}
